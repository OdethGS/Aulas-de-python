# Operadores Relacionais 
# Exemplo Operadores

# Maior que >
# Menor que <
# Maior ou igual >=
# Menor ou igual <=
# igual a ==
# Diferentee de !=

# Esses operadores de volvem valores true ou false

valorA= int(input("Qual é o valor A? "))
valorB= int(input("Qual é o valor B? "))

print( valorA > valorB)
print( valorA < valorB)
print( valorA >= valorB)
print( valorA <= valorB)
print( valorA == valorB)
print( valorA != valorB)
